import type { RegisteredEvent } from "./selection.js";

export interface GeneratedBindings {
  relativePath: string;
  content: string;
  bindInstruction: string;
  lifecycleMode: "stateful" | "per-user";
  language: "typescript" | "javascript" | "swift" | "dart" | "python" | "php";
}

type BindingsTarget = GeneratedBindings["language"];

export function bindingsTargetFor(target: string, sourceFiles: string[] = []): BindingsTarget {
  switch (target) {
    case "swift":
      return "swift";
    case "flutter":
      return "dart";
    case "python":
      return "python";
    case "php":
      return "php";
    case "node":
    case "nextjs":
    case "web-js":
    case "react-native":
      return sourceFiles.some((file) => /\.(?:js|jsx|mjs|cjs)$/.test(file)) &&
          !sourceFiles.some((file) => /\.(?:ts|tsx)$/.test(file))
        ? "javascript"
        : "typescript";
    default:
      return "typescript";
  }
}

function camelCase(code: string): string {
  return code
    .split("_")
    .map((part, index) => (index === 0 ? part : part.charAt(0).toUpperCase() + part.slice(1)))
    .join("");
}

function pascalCase(code: string): string {
  const camel = camelCase(code);
  return camel.charAt(0).toUpperCase() + camel.slice(1);
}

function typescriptTypeFor(type: string): string {
  if (type === "integer") return "number";
  return ["string", "number", "boolean", "null"].includes(type) ? type : "WhisperrPayloadValue";
}

function swiftTypeFor(type: string): string {
  return ({ string: "String", number: "Double", integer: "Int", boolean: "Bool", null: "NSNull" } as Record<string, string>)[type] ?? "String";
}

function dartTypeFor(type: string): string {
  return ({ string: "String", number: "num", integer: "int", boolean: "bool", null: "Null" } as Record<string, string>)[type] ?? "Object";
}

export function generateBindings(
  target: string,
  events: RegisteredEvent[],
  sourceFiles: string[] = [],
): GeneratedBindings {
  const language = bindingsTargetFor(target, sourceFiles);
  switch (language) {
    case "swift":
      return generateSwift(events);
    case "dart":
      return generateDart(events);
    case "python":
      return generatePython(events);
    case "php":
      return generatePhp(events);
    case "javascript":
      return target === "node" ? generateNode(events, true) : generateTypeScript(events, true);
    default:
      return target === "node" ? generateNode(events, false) : generateTypeScript(events, false);
  }
}

function generateTypeScript(events: RegisteredEvent[], javascript: boolean): GeneratedBindings {
  const ext = javascript ? "js" : "ts";
  const lines: string[] = [
    "// Generated by @whisperr/wizard — do not edit by hand.",
    "// Call bindWhisperr(client) once right after the Whisperr SDK is initialized;",
    "// events tracked before binding are queued, never dropped.",
    "",
    ...(javascript ? [] : [
      "type WhisperrPayloadValue = string | number | boolean | null;",
      "type WhisperrClientLike = {",
      "  track: (event: string, payload?: Record<string, WhisperrPayloadValue>) => unknown;",
      "};",
    ]),
    "",
    javascript ? "let boundClient = null;" : "let boundClient: WhisperrClientLike | null = null;",
    javascript ? "const queued = [];" : "const queued: Array<[string, Record<string, WhisperrPayloadValue> | undefined]> = [];",
    "",
    javascript ? "export function bindWhisperr(client) {" : "export function bindWhisperr(client: WhisperrClientLike): void {",
    "  boundClient = client;",
    "  while (queued.length > 0) {",
    javascript ? "    const [event, payload] = queued.shift();" : "    const [event, payload] = queued.shift()!;",
    "    try { client.track(event, payload); } catch { /* analytics must never break the app */ }",
    "  }",
    "}",
    "",
    javascript ? "function emit(event, payload) {" : "function emit(event: string, payload?: Record<string, WhisperrPayloadValue>): void {",
    "  if (boundClient) {",
    "    try { boundClient.track(event, payload); } catch { /* analytics must never break the app */ }",
    "  } else {",
    "    queued.push([event, payload]);",
    "  }",
    "}",
    "",
    "export const WhisperrEvents = {",
  ];
  for (const event of events) {
    const fields = Object.keys(event.payloadSchema);
    for (const field of fields) {
      lines.push(`  /** ${field}: ${event.payloadSchema[field]} */`);
    }
    if (fields.length === 0) {
      lines.push(javascript ? `  ${camelCase(event.code)}() {` : `  ${camelCase(event.code)}(): void {`, `    emit("${event.code}");`, "  },");
    } else {
      const params = fields.map((field) => `${camelCase(field)}: ${typescriptTypeFor(event.payloadSchema[field] ?? "")}`).join("; ");
      const entries = fields.map((field) => `"${field}": ${camelCase(field)}`).join(", ");
      lines.push(
        javascript ? `  ${camelCase(event.code)}(payload) {` : `  ${camelCase(event.code)}(payload: { ${params} }): void {`,
        `    const { ${fields.map((field) => camelCase(field)).join(", ")} } = payload;`,
        `    emit("${event.code}", { ${entries} });`,
        "  },",
      );
    }
  }
  lines.push("};", "");
  return {
    relativePath: `whisperr-events.${ext}`,
    content: lines.join("\n"),
    bindInstruction:
      "Import { bindWhisperr } from the generated whisperr-events module and call bindWhisperr(client) once, immediately after the Whisperr SDK client is created at app startup.",
    lifecycleMode: "stateful",
    language: javascript ? "javascript" : "typescript",
  };
}

function generateNode(events: RegisteredEvent[], javascript: boolean): GeneratedBindings {
  const lines = [
    "// Generated by @whisperr/wizard — do not edit by hand.",
    "// Server wrappers require an external user ID on every call.",
    "",
    ...(javascript ? [] : [
      "type WhisperrPayloadValue = string | number | boolean | null;",
      "type WhisperrServerClientLike = { track: (userId: string, event: string, payload?: Record<string, WhisperrPayloadValue>) => unknown };",
    ]),
    javascript ? "let boundClient = null;" : "let boundClient: WhisperrServerClientLike | null = null;",
    javascript ? "export function bindWhisperr(client) { boundClient = client; }" : "export function bindWhisperr(client: WhisperrServerClientLike): void { boundClient = client; }",
    javascript ? "function emit(userId, event, payload) {" : "function emit(userId: string, event: string, payload?: Record<string, WhisperrPayloadValue>): void {",
    "  if (!boundClient) throw new Error('Whisperr bindings are not initialized');",
    "  try { boundClient.track(userId, event, payload); } catch { /* analytics must never break the app */ }",
    "}", "", "export const WhisperrEvents = {",
  ];
  for (const event of events) {
    const fields = Object.keys(event.payloadSchema);
    const signature = fields.length === 0
      ? (javascript ? "externalUserId" : "externalUserId: string")
      : (javascript ? "externalUserId, payload" : `externalUserId: string, payload: { ${fields.map((f) => `${camelCase(f)}: ${typescriptTypeFor(event.payloadSchema[f] ?? "")}`).join("; ")} }`);
    lines.push(`  ${camelCase(event.code)}(${signature})${javascript ? "" : ": void"} {`);
    if (fields.length === 0) lines.push(`    emit(externalUserId, "${event.code}");`);
    else {
      lines.push(`    const { ${fields.map(camelCase).join(", ")} } = payload;`);
      lines.push(`    emit(externalUserId, "${event.code}", { ${fields.map((f) => `"${f}": ${camelCase(f)}`).join(", ")} });`);
    }
    lines.push("  },");
  }
  lines.push("};", "");
  return { relativePath: `whisperr-events.${javascript ? "js" : "ts"}`, content: lines.join("\n"), bindInstruction: "Call bindWhisperr(client) once after creating the process-wide server client. Every generated wrapper requires the external user ID as its first argument.", lifecycleMode: "per-user", language: javascript ? "javascript" : "typescript" };
}

function generateSwift(events: RegisteredEvent[]): GeneratedBindings {
  const lines: string[] = [
    "// Generated by @whisperr/wizard — do not edit by hand.",
    "// Call WhisperrEvents.bind(track:) once right after the Whisperr SDK is ready;",
    "// events tracked before binding are queued, never dropped.",
    "",
    "import Foundation",
    "",
    "enum WhisperrEvents {",
    "    typealias TrackFunction = (String, [String: Any]) -> Void",
    "    private static var boundTrack: TrackFunction?",
    "    private static var queued: [(String, [String: Any])] = []",
    "    private static let lock = NSLock()",
    "",
    "    static func bind(track: @escaping TrackFunction) {",
    "        lock.lock()",
    "        boundTrack = track",
    "        let pending = queued",
    "        queued.removeAll()",
    "        lock.unlock()",
    "        for (event, payload) in pending { track(event, payload) }",
    "    }",
    "",
    "    private static func emit(_ event: String, _ payload: [String: Any] = [:]) {",
    "        lock.lock()",
    "        if let track = boundTrack {",
    "            lock.unlock()",
    "            track(event, payload)",
    "        } else {",
    "            queued.append((event, payload))",
    "            lock.unlock()",
    "        }",
    "    }",
    "",
  ];
  for (const event of events) {
    const fields = Object.keys(event.payloadSchema);
    for (const field of fields) {
      lines.push(`    /// ${field}: ${event.payloadSchema[field]}`);
    }
    if (fields.length === 0) {
      lines.push(`    static func ${camelCase(event.code)}() {`, `        emit("${event.code}")`, "    }", "");
    } else {
      const params = fields.map((field) => `${camelCase(field)}: ${swiftTypeFor(event.payloadSchema[field] ?? "")}`).join(", ");
      const entries = fields.map((field) => `"${field}": ${camelCase(field)}`).join(", ");
      lines.push(
        `    static func ${camelCase(event.code)}(${params}) {`,
        `        emit("${event.code}", [${entries}])`,
        "    }",
        "",
      );
    }
  }
  lines.push("}", "");
  return {
    relativePath: "WhisperrEvents.swift",
    content: lines.join("\n"),
    bindInstruction:
      "Call WhisperrEvents.bind(track:) once, immediately after Whisperr SDK initialization completes, forwarding the typed JSON payload to the SDK's track call without converting values to strings.",
    lifecycleMode: "stateful",
    language: "swift",
  };
}

function generateDart(events: RegisteredEvent[]): GeneratedBindings {
  const lines: string[] = [
    "// Generated by @whisperr/wizard — do not edit by hand.",
    "// Call WhisperrEvents.bind(track) once right after the Whisperr SDK is ready;",
    "// events tracked before binding are queued, never dropped.",
    "",
    "typedef WhisperrTrack = void Function(String event, Map<String, Object?> payload);",
    "",
    "class WhisperrEvents {",
    "  static WhisperrTrack? _track;",
    "  static final List<MapEntry<String, Map<String, Object?>>> _queued = [];",
    "",
    "  static void bind(WhisperrTrack track) {",
    "    _track = track;",
    "    for (final entry in _queued) {",
    "      track(entry.key, entry.value);",
    "    }",
    "    _queued.clear();",
    "  }",
    "",
    "  static void _emit(String event, [Map<String, Object?> payload = const {}]) {",
    "    final track = _track;",
    "    if (track != null) {",
    "      track(event, payload);",
    "    } else {",
    "      _queued.add(MapEntry(event, payload));",
    "    }",
    "  }",
    "",
  ];
  for (const event of events) {
    const fields = Object.keys(event.payloadSchema);
    for (const field of fields) {
      lines.push(`  /// ${field}: ${event.payloadSchema[field]}`);
    }
    if (fields.length === 0) {
      lines.push(`  static void ${camelCase(event.code)}() => _emit('${event.code}');`, "");
    } else {
      const params = fields.map((field) => `required ${dartTypeFor(event.payloadSchema[field] ?? "")} ${camelCase(field)}`).join(", ");
      const entries = fields.map((field) => `'${field}': ${camelCase(field)}`).join(", ");
      lines.push(
        `  static void ${camelCase(event.code)}({${params}}) =>`,
        `      _emit('${event.code}', {${entries}});`,
        "",
      );
    }
  }
  lines.push("}", "");
  return {
    relativePath: "whisperr_events.dart",
    content: lines.join("\n"),
    bindInstruction:
      "Call WhisperrEvents.bind(track) once, immediately after the Whisperr SDK is initialized, forwarding to the SDK's track call.",
    lifecycleMode: "stateful",
    language: "dart",
  };
}

function generatePython(events: RegisteredEvent[]): GeneratedBindings {
  const lines = [
    "# Generated by @whisperr/wizard — do not edit by hand.",
    "# Server wrappers require an external user ID on every call.",
    "", "_client = None", "", "def bind_whisperr(client):", "    global _client", "    _client = client", "",
    "def _emit(external_user_id, event, properties=None):", "    if _client is None:", "        raise RuntimeError('Whisperr bindings are not initialized')", "    try:", "        _client.track(external_user_id, event, properties or {})", "    except Exception:", "        pass", "",
    "class WhisperrEvents:",
  ];
  if (events.length === 0) lines.push("    pass");
  for (const event of events) {
    const fields = Object.keys(event.payloadSchema);
    const args = fields.join(", ");
    lines.push("    @staticmethod", `    def ${event.code}(external_user_id${args ? `, ${args}` : ""}):`);
    lines.push(fields.length ? `        _emit(external_user_id, "${event.code}", {${fields.map((f) => `"${f}": ${f}`).join(", ")}})` : `        _emit(external_user_id, "${event.code}")`, "");
  }
  return { relativePath: "whisperr_events.py", content: lines.join("\n"), bindInstruction: "Import bind_whisperr and call it once with the shared process client. Every wrapper requires external_user_id first.", lifecycleMode: "per-user", language: "python" };
}

function generatePhp(events: RegisteredEvent[]): GeneratedBindings {
  const lines = ["<?php", "// Generated by @whisperr/wizard — do not edit by hand.", "final class WhisperrEvents", "{", "    private static $client;", "", "    public static function bindWhisperr($client): void { self::$client = $client; }", ""];
  for (const event of events) {
    const fields = Object.keys(event.payloadSchema);
    const args = fields.map((f) => `$${camelCase(f)}`).join(", ");
    lines.push(`    public static function ${camelCase(event.code)}($externalUserId${args ? `, ${args}` : ""}): void`, "    {", "        if (!self::$client) { throw new \\RuntimeException('Whisperr bindings are not initialized'); }");
    lines.push(`        try { self::$client->track($externalUserId, '${event.code}', [${fields.map((f) => `'${f}' => $${camelCase(f)}`).join(", ")}]); } catch (\\Throwable $ignored) {}`, "    }", "");
  }
  lines.push("}", "");
  return { relativePath: "WhisperrEvents.php", content: lines.join("\n"), bindInstruction: "Call WhisperrEvents::bindWhisperr($client) once with the shared server client. Every wrapper requires the external user ID first.", lifecycleMode: "per-user", language: "php" };
}

export function bindingsClassName(target: string): string {
  return bindingsTargetFor(target) === "typescript" ? "WhisperrEvents" : "WhisperrEvents";
}

export function eventWrapperName(code: string, target = ""): string {
  if (target === "php") return `WhisperrEvents::${camelCase(code)}`;
  if (target === "python") return `WhisperrEvents.${code}`;
  return `${bindingsClassName(target)}.${camelCase(code)}`;
}

